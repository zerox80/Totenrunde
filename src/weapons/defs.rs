//! Waffendaten. Werte orientieren sich an BO2-Zombies (Schaden pro Kugel, Magazin,
//! Reserve, Feuerrate), Namen der Upgrades sind eigene Erfindungen.

use bevy::prelude::*;

use crate::audio::Sfx;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum WeaponClass {
    Pistol,
    Smg,
    Rifle,
    Shotgun,
    Lmg,
    Sniper,
    Launcher,
    Wonder,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum FireMode {
    Semi,
    Auto,
    Burst(u32),
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Projectile {
    Hitscan,
    RayBolt,
    Grenade,
}

#[derive(Clone, Copy, Debug)]
pub struct PapStats {
    pub damage_mult: f32,
    pub mag: u32,
    pub reserve: u32,
    pub rpm_mult: f32,
    /// Explosionsradius (0 = keine), z. B. für die aufgewertete Pistole
    pub splash: f32,
    pub splash_damage: f32,
}

#[derive(Clone, Copy, Debug)]
pub struct WeaponDef {
    pub id: &'static str,
    pub name: &'static str,
    pub pap_name: &'static str,
    pub class: WeaponClass,
    pub fire: FireMode,
    pub damage: f32,
    pub head_mult: f32,
    pub pellets: u32,
    pub rpm: f32,
    pub mag: u32,
    pub reserve: u32,
    pub reload: f32,
    pub reload_empty: f32,
    /// Schrotflinten laden Patrone für Patrone
    pub shell_reload: bool,
    pub spread_hip: f32,
    pub spread_ads: f32,
    pub recoil: f32,
    pub recoil_side: f32,
    pub penetration: u32,
    pub range: f32,
    pub ads_zoom: f32,
    pub mobility: f32,
    pub projectile: Projectile,
    pub splash: f32,
    pub splash_damage: f32,
    pub wall_cost: u32,
    pub box_weight: f32,
    pub sound: Sfx,
    pub pap: PapStats,
    /// Waffenposition (Kameraraum, Meter) in der Hüfte und beim Zielen
    pub hip: Vec3,
    pub ads: Vec3,
    pub scope: bool,
}

impl WeaponDef {
    pub fn model(&self) -> String {
        format!("models/weapons/{}.gltf", self.id)
    }
    pub fn ammo_cost(&self) -> u32 {
        self.wall_cost / 2
    }
    pub fn display_name(&self, upgraded: bool) -> &'static str {
        if upgraded {
            self.pap_name
        } else {
            self.name
        }
    }
    pub fn mag_size(&self, upgraded: bool) -> u32 {
        if upgraded {
            self.pap.mag
        } else {
            self.mag
        }
    }
    pub fn reserve_size(&self, upgraded: bool) -> u32 {
        if upgraded {
            self.pap.reserve
        } else {
            self.reserve
        }
    }
}

const fn pap(damage_mult: f32, mag: u32, reserve: u32) -> PapStats {
    PapStats {
        damage_mult,
        mag,
        reserve,
        rpm_mult: 1.0,
        splash: 0.0,
        splash_damage: 0.0,
    }
}

